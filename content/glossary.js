// מחזיר את המושגים מהיחידות עד (וכולל) היחידה הנתונה, לפי סדר הרצף.
// כל מושג מסומן isNew אם הוא מופיע לראשונה דווקא ביחידה הנוכחית.
export function glossaryUpTo(unitId) {
  const order = allUnits.map((u) => u.id);
  const curIdx = order.indexOf(unitId);
  if (curIdx < 0) return [];
  return glossary
    .filter((g) => {
      const i = order.indexOf(g.unit);
      return i !== -1 && i <= curIdx;
    })
    .map((g) => ({ ...g, isNew: g.unit === unitId }));
}
